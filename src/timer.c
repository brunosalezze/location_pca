/**
 * @file timer.c
 * @brief Monotonic clock based on POSIX clock_gettime().
 */
#define _POSIX_C_SOURCE 200809L

#include "timer.h"

#include <time.h>

double timer_now(void)
{
    struct timespec now;
    clock_gettime(CLOCK_MONOTONIC, &now);
    return (double)now.tv_sec + (double)now.tv_nsec * 1e-9;
}
